#!/bin/bash
# The table of bundled GStreamer libraries in THIRD-PARTY-NOTICES.md, generated
# from a collected lib directory so that it cannot drift from what ships.
#
#   scripts/macos/gstreamer-notices.sh --check    <gstreamer prefix> <lib dir>
#   scripts/macos/gstreamer-notices.sh --write    <gstreamer prefix> <lib dir>
#   scripts/macos/gstreamer-notices.sh --projects <gstreamer prefix> <lib dir>
#
# --check fails if the table between the markers in THIRD-PARTY-NOTICES.md differs
# from the one generated; --write replaces it; --projects prints the projects
# (cerbero recipe names, the directory names under <prefix>/share/licenses).
# Every file in the lib directory must map to a project below; versions come
# from <prefix>/share/versions.txt, which the official packages ship.

set -euo pipefail
set -f

die() {
    printf 'gstreamer-notices: error: %s\n' "$*" >&2
    exit 1
}

[ "$#" = 3 ] || die "usage: $0 --check|--write|--projects <gstreamer prefix> <lib dir>"
MODE="$1"
PREFIX="$2"
LIB_DIR="$3"
REPOSITORY="$(cd "$(dirname -- "$0")/../.." && pwd -P)"
NOTICES="$REPOSITORY/THIRD-PARTY-NOTICES.md"
BEGIN='<!-- gstreamer-libraries:begin (generated by scripts/macos/gstreamer-notices.sh; do not edit) -->'
END='<!-- gstreamer-libraries:end -->'

VERSIONS_FILE="$PREFIX/share/versions.txt"
[ -f "$VERSIONS_FILE" ] || die "$VERSIONS_FILE is missing (the development package is needed)"
[ -d "$LIB_DIR" ] || die "$LIB_DIR is not a directory"

# The project (cerbero recipe) a bundled file comes from.
project_of() {
    case "$1" in
        libgstreamer-1.0.0.dylib | libgstbase-1.0.0.dylib | libgstcontroller-1.0.0.dylib | \
            libgstnet-1.0.0.dylib | libgstcoreelements.dylib)
            echo gstreamer-1.0 ;;
        libgstapp-1.0.0.dylib | libgstaudio-1.0.0.dylib | libgstfft-1.0.0.dylib | \
            libgstgl-1.0.0.dylib | libgstpbutils-1.0.0.dylib | libgstriff-1.0.0.dylib | \
            libgstrtp-1.0.0.dylib | libgstsdp-1.0.0.dylib | libgsttag-1.0.0.dylib | \
            libgstvideo-1.0.0.dylib | libgstapp.dylib | libgstaudioconvert.dylib | \
            libgstaudioresample.dylib | libgstgio.dylib | libgstogg.dylib | \
            libgstopengl.dylib | libgstopus.dylib | libgstplayback.dylib | \
            libgsttheora.dylib | libgsttypefindfunctions.dylib | \
            libgstvideoconvertscale.dylib | libgstvolume.dylib | libgstvorbis.dylib)
            echo gst-plugins-base-1.0 ;;
        libgstaudiofx.dylib | libgstaudioparsers.dylib | libgstautodetect.dylib | \
            libgstdeinterlace.dylib | libgstid3demux.dylib | libgstinterleave.dylib | \
            libgstisomp4.dylib | libgstmatroska.dylib | libgstrtp.dylib | \
            libgstrtpmanager.dylib | libgstvideofilter.dylib | libgstvpx.dylib | \
            libgstwavparse.dylib | libgstosxaudio.dylib | libgstosxvideo.dylib)
            echo gst-plugins-good-1.0 ;;
        libgstcodecparsers-1.0.0.dylib | libgstplay-1.0.0.dylib | libgstsctp-1.0.0.dylib | \
            libgstvulkan-1.0.0.dylib | libgstwebrtc-1.0.0.dylib | \
            libgstwebrtcnice-1.0.0.dylib | libgstaudiobuffersplit.dylib | libgstdtls.dylib | \
            libgstid3tag.dylib | libgstproxy.dylib | libgstvideoparsersbad.dylib | \
            libgstwebrtc.dylib | libgstapplemedia.dylib)
            echo gst-plugins-bad-1.0 ;;
        libgstlibav.dylib) echo gst-libav-1.0 ;;
        libavcodec.*.dylib | libavfilter.*.dylib | libavformat.*.dylib | libavutil.*.dylib | \
            libswresample.*.dylib | libswscale.*.dylib)
            echo ffmpeg ;;
        libglib-2.0.0.dylib | libgobject-2.0.0.dylib | libgio-2.0.0.dylib | libgmodule-2.0.0.dylib)
            echo glib ;;
        libgstnice.dylib | libnice.*.dylib) echo libnice ;;
        libintl.*.dylib) echo proxy-libintl ;;
        libffi.*.dylib) echo libffi ;;
        libpcre2-8.*.dylib) echo pcre2 ;;
        libz.*.dylib) echo zlib ;;
        libbz2.*.dylib) echo bzip2 ;;
        libogg.*.dylib) echo libogg ;;
        libvorbis.*.dylib | libvorbisenc.*.dylib) echo libvorbis ;;
        libtheoradec.*.dylib | libtheoraenc.*.dylib) echo libtheora ;;
        libopus.*.dylib) echo opus ;;
        libvpx.*.dylib) echo libvpx ;;
        libcrypto.*.dylib | libssl.*.dylib) echo openssl ;;
        liborc-0.4.*.dylib) echo orc ;;
        libgraphene-1.0.*.dylib) echo graphene ;;
        libpng16.*.dylib) echo libpng ;;
        libjpeg.*.dylib) echo libjpeg-turbo ;;
        libMoltenVK.dylib) echo moltenvk ;;
        *) return 1 ;;
    esac
}

# The licence of a project, as stated in the package's
# share/licenses/<project>/README-LICENSE-INFO.txt (SPDX identifiers). The two
# gst-plugins-good and gst-libav have no licence directory in the package; their
# upstream licence is LGPL-2.1-or-later.
licence_of() {
    case "$1" in
        gstreamer-1.0 | gst-plugins-base-1.0 | glib | proxy-libintl) echo "LGPL-2.0-or-later" ;;
        gst-plugins-bad-1.0) echo "LGPL-2.0-or-later (usrsctp in libgstsctp: BSD-3-Clause)" ;;
        gst-plugins-good-1.0 | gst-libav-1.0 | ffmpeg) echo "LGPL-2.1-or-later" ;;
        libnice) echo "LGPL-2.1-or-later OR MPL-1.1" ;;
        bzip2) echo "bzip2-1.0.6" ;;
        libffi | graphene) echo "MIT" ;;
        libjpeg-turbo) echo "IJG AND BSD-3-Clause AND Zlib" ;;
        libogg | libvorbis | libtheora | opus) echo "BSD-3-Clause" ;;
        libvpx) echo "BSD-3-Clause (with the WebM patent grant)" ;;
        openssl | moltenvk) echo "Apache-2.0" ;;
        orc) echo "BSD-2-Clause" ;;
        pcre2) echo "BSD-3-Clause WITH PCRE2-exception" ;;
        libpng) echo "libpng-2.0" ;;
        zlib) echo "Zlib" ;;
        *) return 1 ;;
    esac
}

# Sets VERSION for project $1. Called in this shell, never in a command substitution, so
# that `die` ends the script.
VERSION=""
version_of() {
    VERSION="$(awk -v name="$1" '$1 == name { print $2 }' "$VERSIONS_FILE")" \
        || die "cannot read $VERSIONS_FILE"
    [ -n "$VERSION" ] || die "no version for $1 in $VERSIONS_FILE"
}

# "project<TAB>file" for every collected file, sorted.
names="$(cd -- "$LIB_DIR" && find . -type f -name '*.dylib' | sed 's|^\./||' | LC_ALL=C sort)" \
    || die "cannot list $LIB_DIR"
[ -n "$names" ] || die "$LIB_DIR holds no libraries"
pairs=""
while IFS= read -r name; do
    project="$(project_of "$name")" || die "$name is not mapped to a project in $0; add it"
    pairs+="$project"$'\t'"$name"$'\n'
done <<<"$names"
pairs="$(LC_ALL=C sort <<<"$pairs" | sed '/^$/d')"
projects="$(cut -f 1 <<<"$pairs" | LC_ALL=C sort -u)"

if [ "$MODE" = --projects ]; then
    printf '%s\n' "$projects"
    exit 0
fi

# The table, built in this shell so that a missing version or licence stops the script.
table="$BEGIN"$'\n'"| Project (cerbero recipe) | Version | Licence | Bundled files |"$'\n'"|---|---|---|---|"$'\n'
while IFS= read -r project; do
    version_of "$project"
    licence="$(licence_of "$project")" || die "no licence recorded for $project in $0"
    files="$(awk -F '\t' -v p="$project" '$1 == p { printf "%s`%s`", (n++ ? ", " : ""), $2 }' <<<"$pairs")" \
        || die "awk failed"
    [ -n "$VERSION" ] || die "empty version for $project"
    [ -n "$files" ] || die "no files for $project"
    table+="| $project | $VERSION | $licence | $files |"$'\n'
done <<<"$projects"
table+="$END"
current="$(awk -v b="$BEGIN" -v e="$END" '$0 == b { on = 1 } on { print } $0 == e { on = 0 }' "$NOTICES")"

case "$MODE" in
    --check)
        [ -n "$current" ] || die "THIRD-PARTY-NOTICES.md has no generated GStreamer table"
        [ "$current" = "$table" ] \
            || die "the GStreamer library table in THIRD-PARTY-NOTICES.md does not match $LIB_DIR"
        ;;
    --write)
        [ -n "$current" ] || die "THIRD-PARTY-NOTICES.md has no begin/end markers for the table"
        tmp="$NOTICES.tmp"
        skip=0
        while IFS= read -r line || [ -n "$line" ]; do
            if [ "$line" = "$BEGIN" ]; then
                printf '%s\n' "$table"
                skip=1
            elif [ "$line" = "$END" ]; then
                skip=0
            elif [ "$skip" = 0 ]; then
                printf '%s\n' "$line"
            fi
        done <"$NOTICES" >"$tmp"
        mv -- "$tmp" "$NOTICES"
        printf 'gstreamer-notices: wrote the table for %s\n' "$LIB_DIR" >&2
        ;;
    *) die "unknown mode $MODE" ;;
esac
