#!/usr/bin/env python3
"""Serve the repository's tests/ directory on the loopback interface, for the media checks.

    python3 scripts/serve-tests.py [--port N]

Binds 127.0.0.1 on an ephemeral port (or --port), prints the port on the first line of
standard output, and serves tests/ (so tests/pages/media.html is /pages/media.html). Single
byte ranges ("Range: bytes=a-b", "a-" and "-n") are answered with 206 Partial Content, as real
media servers do; python's own http.server ignores Range. Exits on SIGINT, SIGTERM or SIGHUP,
and when the process that started it goes away. Standard library only.

Downloads: /download/<name> (GET or POST) answers generated bytes (byte i is i % 251) with a
strong ETag, a Last-Modified date and Range support. Query parameters: size (bytes, default
1000), type (Content-Type, default application/octet-stream), disposition (attachment or
inline; omitted by default), filename (for disposition), body=png (a 64x64 red PNG instead of
the generated bytes; size is then ignored), body=text (lines of ASCII text, size bytes), rate (bytes per second; 0, the
default, is unthrottled), setcookie (a Set-Cookie value). --log FILE appends one JSON line per
request: method, path, Cookie, Referer, User-Agent, Range, the bytes of the body sent and
whether the client read it to the end. POST /form-result answers a page that follows a link to
a file by itself.
"""

import argparse
import json
import os
import re
import signal
import sys
import struct
import threading
import time
import zlib
from email.utils import formatdate
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, quote, urlsplit

RANGE = re.compile(r"^bytes=(\d*)-(\d*)$")
REQUEST_LOG = None
LOG_LOCK = threading.Lock()
# A fixed date, so a resumed download sees the same validator as the first attempt.
LAST_MODIFIED = formatdate(1_700_000_000, usegmt=True)


def red_png(side=64):
    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

    rows = b"".join(b"\x00" + b"\xff\x00\x00" * side for _ in range(side))
    header = struct.pack(">IIBBBBB", side, side, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows))
            + chunk(b"IEND", b""))


def log_request(handler, sent, complete):
    if REQUEST_LOG is None:
        return
    entry = {
        "method": handler.command,
        "path": handler.path,
        "cookie": handler.headers.get("Cookie"),
        "referer": handler.headers.get("Referer"),
        "user_agent": handler.headers.get("User-Agent"),
        "range": handler.headers.get("Range"),
        "sent": sent,
        "complete": complete,
    }
    with LOG_LOCK, open(REQUEST_LOG, "a", encoding="utf-8") as log:
        log.write(json.dumps(entry) + "\n")


class Handler(SimpleHTTPRequestHandler):
    def log_message(self, format, *args):  # quiet: the callers print their own results
        pass

    def end_headers(self):
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def do_GET(self):
        if urlsplit(self.path).path.startswith("/download/"):
            return self.send_download()
        result = super().do_GET()
        log_request(self, None, None)
        return result

    def do_POST(self):
        length = int(self.headers.get("Content-Length") or 0)
        if length:
            self.rfile.read(length)
        if urlsplit(self.path).path.startswith("/download/"):
            return self.send_download()
        if urlsplit(self.path).path == "/form-result":
            return self.send_form_result()
        self.send_error(405)
        log_request(self, None, None)
        return None

    def send_form_result(self):
        # The answer to a form's POST: a page that follows a link to a file on its own, to see
        # what going back to it does (whether the form is sent again).
        body = (b"<!doctype html><title>Form result</title><h1>Form result</h1>"
                b"<a id=f href='/download/after-post.zip?type=application/zip'>file</a>"
                b"<script>setTimeout(() => document.getElementById('f').click(), 500)</script>")
        self.send_response(200)
        self.send_header("Content-Type", "text/html")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
        log_request(self, len(body), True)
        return None

    def send_download(self):
        parts = urlsplit(self.path)
        query = {key: values[-1] for key, values in parse_qs(parts.query).items()}
        png = red_png() if query.get("body") == "png" else None
        size = len(png) if png else int(query.get("size", "1000"))
        if query.get("body") == "text":
            png = b"".join(b"line %d\n" % n for n in range(size))[:size]
        rate = int(query.get("rate", "0"))
        content_type = query.get("type", "application/octet-stream")
        etag = '"%d-%s"' % (size, quote(content_type, safe=""))
        start, end, status = 0, size - 1, 200
        header = self.headers.get("Range")
        match = RANGE.match(header.strip()) if header else None
        if match and match.group(1) and (self.headers.get("If-Range") in (None, etag, LAST_MODIFIED)):
            start = int(match.group(1))
            end = min(int(match.group(2)), size - 1) if match.group(2) else size - 1
            status = 206
            if start >= size:
                self.send_response(416)
                self.send_header("Content-Range", "bytes */%d" % size)
                self.send_header("Content-Length", "0")
                self.end_headers()
                log_request(self, 0, True)
                return None
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(end - start + 1))
        self.send_header("ETag", etag)
        self.send_header("Last-Modified", LAST_MODIFIED)
        if status == 206:
            self.send_header("Content-Range", "bytes %d-%d/%d" % (start, end, size))
        disposition = query.get("disposition")
        if disposition:
            filename = query.get("filename")
            if filename:
                disposition += '; filename="%s"' % filename
            self.send_header("Content-Disposition", disposition)
        if "setcookie" in query:
            self.send_header("Set-Cookie", query["setcookie"])
        self.end_headers()
        sent = 0
        position = start
        chunk_size = max(1, min(65536, rate // 10)) if rate else 65536
        try:
            while position <= end:
                count = min(chunk_size, end - position + 1)
                if png:
                    self.wfile.write(png[position:position + count])
                else:
                    self.wfile.write(bytes((position + i) % 251 for i in range(count)))
                self.wfile.flush()
                position += count
                sent += count
                if rate:
                    time.sleep(count / rate)
        except (BrokenPipeError, ConnectionResetError):
            log_request(self, sent, False)
            return None
        log_request(self, sent, True)
        return None

    def send_head(self):
        self._remaining = None
        header = self.headers.get("Range")
        path = self.translate_path(self.path)
        if header is None or os.path.isdir(path) or not os.path.isfile(path):
            return super().send_head()
        match = RANGE.match(header.strip())
        if match is None or (match.group(1) == "" and match.group(2) == ""):
            return super().send_head()  # several ranges or another unit: send it whole
        size = os.path.getsize(path)
        first, last = match.group(1), match.group(2)
        if first == "":  # the last n bytes
            start, end = max(0, size - int(last)), size - 1
        else:
            start = int(first)
            end = min(int(last), size - 1) if last else size - 1
        if size == 0 or start >= size or start > end:
            self.send_response(416)
            self.send_header("Content-Range", "bytes */%d" % size)
            self.send_header("Content-Length", "0")
            self.end_headers()
            return None
        handle = open(path, "rb")
        handle.seek(start)
        self.send_response(206)
        self.send_header("Content-Type", self.guess_type(path))
        self.send_header("Content-Range", "bytes %d-%d/%d" % (start, end, size))
        self.send_header("Content-Length", str(end - start + 1))
        self.end_headers()
        self._remaining = end - start + 1
        return handle

    def copyfile(self, source, outputfile):
        if self._remaining is None:
            return super().copyfile(source, outputfile)
        remaining = self._remaining
        while remaining > 0:
            chunk = source.read(min(65536, remaining))
            if not chunk:
                break
            outputfile.write(chunk)
            remaining -= len(chunk)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--port", type=int, default=0, help="port to bind (default: any free port)")
    parser.add_argument("--log", help="append one JSON line per request to this file")
    arguments = parser.parse_args()
    global REQUEST_LOG
    REQUEST_LOG = os.path.abspath(arguments.log) if arguments.log else None

    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, "tests")
    os.chdir(os.path.realpath(root))
    server = ThreadingHTTPServer(("127.0.0.1", arguments.port), Handler)
    server.daemon_threads = True

    def stop(*_):
        threading.Thread(target=server.shutdown, daemon=True).start()

    for signal_number in (signal.SIGINT, signal.SIGTERM, signal.SIGHUP):
        signal.signal(signal_number, stop)

    parent = os.getppid()
    if parent == 1:  # the starting process has already gone: nobody will stop this server
        server.server_close()
        return 0

    def watch_parent():
        while os.getppid() == parent:
            time.sleep(0.5)
        stop()

    threading.Thread(target=watch_parent, daemon=True).start()

    print(server.server_address[1], flush=True)
    try:
        server.serve_forever(poll_interval=0.2)
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
